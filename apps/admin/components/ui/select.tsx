function SelectItem({
  className,
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Item>) {
  return (
    <SelectPrimitive.Item
      data-slot="select-item"
      /* The highlight is --accent, and this is the one place --dusk-amber is
       * allowed to carry meaning: it marks where the keyboard is, not what is
       * chosen. Its ~2.70:1 against --ivory would fail as text or as a focus
       * ring, which is why globals.css keeps it out of both — here it is a
       * fill behind --accent-foreground (--ink on amber, 5.67:1).
       *
       * `outline-hidden` stays, and this is the one place a control suppresses
       * the outline globals.css draws. Radix moves real DOM focus onto the
       * highlighted item, so the fill and an outline would both fire — and the
       * outline is drawn at 2px *outside* the element, which on a row inset
       * 1px from the panel edge clips against it. The fill is the indicator
       * here, and it is a stronger one: an amber band across the full row
       * rather than a hairline around it. */
      className={cn(
        "relative flex w-full cursor-default items-center gap-2 rounded-sm py-1.5 pr-8 pl-2 text-sm outline-hidden select-none focus:bg-accent focus:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 [&_svg:not([class*='text-'])]:text-muted-foreground *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
        className,
      )}
      {...props}
    >
      <span
        data-slot="select-item-indicator"
        className="absolute right-2 flex size-3.5 items-center justify-center"
      >
        <SelectPrimitive.ItemIndicator>
          <CheckIcon className="size-4" />
        </SelectPrimitive.ItemIndicator>
      </span>
      <SelectPrimitive.ItemText>{children}</SelectPrimitive.ItemText>
    </SelectPrimitive.Item>
  );
}

